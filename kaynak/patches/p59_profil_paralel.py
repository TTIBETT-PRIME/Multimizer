# -*- coding: utf-8 -*-
"""Acilis hizlandirma (10.0.0): Get-SystemProfile icinde Storage modulu sorgulari (Get-Partition/Get-PhysicalDisk) profil adimlariyla
paralel bir calisma alaninda yurutulur; bos/toplam alan .NET DriveInfo ile aninda okunur (Get-Volume yalniz yedek yol).
Gercek bilgisayar olcumu: bu iki adim acilista 1,2-3,7 sn tutuyordu. Sonuc ayni; zaman asiminda (25 sn) disk turu bos birakilir."""


def apply(b):
    # --- yardimci islevler + paralel baslatma
    b.rep("function Get-SystemProfile {\n    Add-ProfMark 'bas'\n    $p = @{\n",
          "# Sistem diski turu/modeli: Storage modulu ilk cagrida yavas yuklenir (1-4 sn); profilin geri kalaniyla paralel bir calisma alaninda yurutulur\n"
          "$script:DiskProbeBlock = {\n"
          "    param([string]$Drive)\n"
          "    $r = @{ Found = $false; Type = ''; Model = ''; Bus = '' }\n"
          "    try {\n"
          "        $part = Get-Partition -DriveLetter $Drive -ErrorAction Stop | Select-Object -First 1\n"
          "        $pd = Get-PhysicalDisk -ErrorAction Stop | Where-Object { [string]$_.DeviceId -eq [string]$part.DiskNumber } | Select-Object -First 1\n"
          "        if ($null -ne $pd) {\n"
          "            $mt  = [string]$pd.MediaType\n"
          "            $bus = [string]$pd.BusType\n"
          "            $spin = -1\n"
          "            if ($null -ne $pd.SpindleSpeed) { $spin = [double]$pd.SpindleSpeed }\n"
          "            if ($mt -eq 'SSD' -or $mt -eq '4' -or $mt -eq 'SCM' -or $mt -eq '5' -or $bus -eq 'NVMe' -or $bus -eq '17') { $r.Type = 'SSD' }\n"
          "            elseif ($mt -eq 'HDD' -or $mt -eq '3') { $r.Type = 'HDD' }\n"
          "            elseif ($spin -eq 0) { $r.Type = 'SSD' }\n"
          "            elseif ($spin -gt 0 -and $spin -lt 20000) { $r.Type = 'HDD' }\n"
          "            $r.Model = [string]$pd.FriendlyName\n"
          "            $r.Bus = $bus\n"
          "            $r.Found = $true\n"
          "        }\n"
          "    } catch { }\n"
          "    return $r\n"
          "}\n\n"
          "function Start-DiskProbe([string]$Drive) {\n"
          "    $o = @{ Ps = $null; Ar = $null; Drive = $Drive }\n"
          "    $ps = $null\n"
          "    try {\n"
          "        $ps = [powershell]::Create()\n"
          "        [void]$ps.AddScript($script:DiskProbeBlock.ToString()).AddArgument($Drive)\n"
          "        $o.Ar = $ps.BeginInvoke()\n"
          "        $o.Ps = $ps\n"
          "    } catch {\n"
          "        try { if ($null -ne $ps) { $ps.Dispose() } } catch { }\n"
          "        $o.Ps = $null\n"
          "        $o.Ar = $null\n"
          "    }\n"
          "    return $o\n"
          "}\n\n"
          "# Paralel sorgunun sonucunu alir; baslatilamamissa ayni sorguyu burada calistirir. Zaman asiminda $null doner (disk turu bos kalir).\n"
          "function Complete-DiskProbe($Probe) {\n"
          "    $res = $null\n"
          "    try {\n"
          "        if ($null -ne $Probe -and $null -ne $Probe.Ps) {\n"
          "            if ($Probe.Ar.AsyncWaitHandle.WaitOne(25000)) {\n"
          "                try {\n"
          "                    $out = @($Probe.Ps.EndInvoke($Probe.Ar))\n"
          "                    if ($out.Count -gt 0) {\n"
          "                        $it = $out[0]\n"
          "                        if ($null -ne $it) {\n"
          "                            $bo = $it.PSObject.BaseObject\n"
          "                            if ($bo -is [hashtable]) { $res = $bo }\n"
          "                        }\n"
          "                    }\n"
          "                } finally { try { $Probe.Ps.Dispose() } catch { } }\n"
          "            } else {\n"
          "                try { [void]$Probe.Ps.BeginStop($null, $null) } catch { }\n"
          "            }\n"
          "        } elseif ($null -ne $Probe -and [string]$Probe.Drive -ne '') {\n"
          "            $res = & $script:DiskProbeBlock ([string]$Probe.Drive)\n"
          "        }\n"
          "    } catch { }\n"
          "    return $res\n"
          "}\n\n"
          "function Get-SystemProfile {\n    Add-ProfMark 'bas'\n"
          "    $sd0 = [string]$env:SystemDrive\n"
          "    if ($sd0 -eq '') { $sd0 = 'C:' }\n"
          "    $diskProbe = Start-DiskProbe ($sd0.TrimEnd(':'))\n"
          "    $p = @{\n",
          raw=True, name='p59 disk sorgusu islevleri')

    # --- bos/toplam alan (DriveInfo) + disk turu sonucu
    old = ("    $p.SysDrive = $env:SystemDrive.TrimEnd(':')\n"
           "    try {\n"
           "        $vol = Get-Volume -DriveLetter $p.SysDrive -ErrorAction Stop\n"
           "        $p.FreeGB = [math]::Round(([double]$vol.SizeRemaining) / 1GB, 1)\n"
           "        $p.SizeGB = [math]::Round(([double]$vol.Size) / 1GB, 1)\n"
           "    } catch {\n"
           "        try {\n"
           "            $drv = Get-PSDrive -Name $p.SysDrive -ErrorAction Stop\n"
           "            $p.FreeGB = [math]::Round(([double]$drv.Free) / 1GB, 1)\n"
           "            $p.SizeGB = [math]::Round(([double]$drv.Used + [double]$drv.Free) / 1GB, 1)\n"
           "        } catch { }\n"
           "    }\n"
           "    Add-ProfMark 'hacim'\n"
           "    try {\n"
           "        $part = Get-Partition -DriveLetter $p.SysDrive -ErrorAction Stop | Select-Object -First 1\n"
           "        $pd = Get-PhysicalDisk -ErrorAction Stop | Where-Object { [string]$_.DeviceId -eq [string]$part.DiskNumber } | Select-Object -First 1\n"
           "        if ($null -ne $pd) {\n"
           "            $mt  = [string]$pd.MediaType\n"
           "            $bus = [string]$pd.BusType\n"
           "            $spin = -1\n"
           "            if ($null -ne $pd.SpindleSpeed) { $spin = [double]$pd.SpindleSpeed }\n"
           "            if ($mt -eq 'SSD' -or $mt -eq '4' -or $mt -eq 'SCM' -or $mt -eq '5' -or $bus -eq 'NVMe' -or $bus -eq '17') { $p.DiskType = 'SSD' }\n"
           "            elseif ($mt -eq 'HDD' -or $mt -eq '3') { $p.DiskType = 'HDD' }\n"
           "            elseif ($spin -eq 0) { $p.DiskType = 'SSD' }\n"
           "            elseif ($spin -gt 0 -and $spin -lt 20000) { $p.DiskType = 'HDD' }\n"
           "            $p.DiskModel = [string]$pd.FriendlyName\n"
           "            $p.BusType = $bus\n"
           "        }\n"
           "    } catch { }\n"
           "    Add-ProfMark 'disk'\n")
    new = ("    $p.SysDrive = $env:SystemDrive.TrimEnd(':')\n"
           "    # Bos/toplam alan: .NET DriveInfo aninda yanit verir; Storage modulu (Get-Volume) yalnizca yedek yol\n"
           "    $volOk = $false\n"
           "    try {\n"
           "        $di = New-Object System.IO.DriveInfo($p.SysDrive)\n"
           "        if ($di.IsReady -and [double]$di.TotalSize -gt 0) {\n"
           "            $p.FreeGB = [math]::Round(([double]$di.TotalFreeSpace) / 1GB, 1)\n"
           "            $p.SizeGB = [math]::Round(([double]$di.TotalSize) / 1GB, 1)\n"
           "            $volOk = $true\n"
           "        }\n"
           "    } catch { }\n"
           "    if (-not $volOk) {\n"
           "        try {\n"
           "            $vol = Get-Volume -DriveLetter $p.SysDrive -ErrorAction Stop\n"
           "            $p.FreeGB = [math]::Round(([double]$vol.SizeRemaining) / 1GB, 1)\n"
           "            $p.SizeGB = [math]::Round(([double]$vol.Size) / 1GB, 1)\n"
           "        } catch {\n"
           "            try {\n"
           "                $drv = Get-PSDrive -Name $p.SysDrive -ErrorAction Stop\n"
           "                $p.FreeGB = [math]::Round(([double]$drv.Free) / 1GB, 1)\n"
           "                $p.SizeGB = [math]::Round(([double]$drv.Used + [double]$drv.Free) / 1GB, 1)\n"
           "            } catch { }\n"
           "        }\n"
           "    }\n"
           "    Add-ProfMark 'hacim'\n"
           "    # Disk turu/modeli: profil adimlariyla paralel baslatilan sorgunun sonucu\n"
           "    try {\n"
           "        $dr = Complete-DiskProbe $diskProbe\n"
           "        if ($null -ne $dr -and $dr.Found -eq $true) {\n"
           "            if ([string]$dr.Type -ne '') { $p.DiskType = [string]$dr.Type }\n"
           "            $p.DiskModel = [string]$dr.Model\n"
           "            $p.BusType = [string]$dr.Bus\n"
           "        }\n"
           "    } catch { }\n"
           "    Add-ProfMark 'disk'\n")
    b.rep(old, new, raw=True, name='p59 depolama blogu')
