          "      <TextBlock x:Name=\"Det\" Text=\"@@Detail@@\" Style=\"{DynamicResource TxtDim}\" FontSize=\"11.5\" TextWrapping=\"Wrap\" Margin=\"0,2,0,0\"/>\n"
          "    </StackPanel>\n"
